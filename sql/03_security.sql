USE DATABASE PIP_QUALITY;
CREATE ROLE IF NOT EXISTS ASSESSMENT_ADMIN;
CREATE ROLE IF NOT EXISTS QA_REVIEWER;
CREATE ROLE IF NOT EXISTS ASSESSOR_TEAM_VIEWER;

CREATE TAG IF NOT EXISTS SECURITY.DIRECT_IDENTIFIER;
CREATE TAG IF NOT EXISTS SECURITY.SPECIAL_CATEGORY;
ALTER TABLE RAW.PEOPLE MODIFY COLUMN claimant_name SET TAG SECURITY.DIRECT_IDENTIFIER='YES';
ALTER TABLE RAW.PEOPLE MODIFY COLUMN ni_number SET TAG SECURITY.DIRECT_IDENTIFIER='YES';
ALTER TABLE RAW.PEOPLE MODIFY COLUMN date_of_birth SET TAG SECURITY.DIRECT_IDENTIFIER='YES';
ALTER TABLE RAW.PEOPLE MODIFY COLUMN health_condition SET TAG SECURITY.SPECIAL_CATEGORY='YES';

CREATE OR REPLACE MASKING POLICY SECURITY.MASK_TEXT AS (v VARCHAR) RETURNS VARCHAR ->
 CASE WHEN IS_ROLE_IN_SESSION('ASSESSMENT_ADMIN') THEN v
      WHEN IS_ROLE_IN_SESSION('QA_REVIEWER') THEN 'REDACTED' ELSE NULL END;
CREATE OR REPLACE MASKING POLICY SECURITY.MASK_DATE AS (v DATE) RETURNS DATE ->
 CASE WHEN IS_ROLE_IN_SESSION('ASSESSMENT_ADMIN') THEN v ELSE NULL END;
CREATE OR REPLACE MASKING POLICY SECURITY.MASK_CATEGORY AS (v VARCHAR) RETURNS VARCHAR ->
 CASE WHEN IS_ROLE_IN_SESSION('ASSESSMENT_ADMIN') OR IS_ROLE_IN_SESSION('QA_REVIEWER')
      THEN v ELSE NULL END;
ALTER VIEW CORE.DIM_CLAIMANT MODIFY COLUMN claimant_name SET MASKING POLICY SECURITY.MASK_TEXT;
ALTER VIEW CORE.DIM_CLAIMANT MODIFY COLUMN ni_number SET MASKING POLICY SECURITY.MASK_TEXT;
ALTER VIEW CORE.DIM_CLAIMANT MODIFY COLUMN date_of_birth SET MASKING POLICY SECURITY.MASK_DATE;
ALTER VIEW CORE.DIM_CLAIMANT MODIFY COLUMN health_condition SET MASKING POLICY SECURITY.MASK_TEXT;
ALTER VIEW CORE.DIM_CLAIMANT MODIFY COLUMN claimant_name SET TAG SECURITY.DIRECT_IDENTIFIER='YES';
ALTER VIEW CORE.DIM_CLAIMANT MODIFY COLUMN ni_number SET TAG SECURITY.DIRECT_IDENTIFIER='YES';
ALTER VIEW CORE.DIM_CLAIMANT MODIFY COLUMN date_of_birth SET TAG SECURITY.DIRECT_IDENTIFIER='YES';
ALTER VIEW CORE.DIM_CLAIMANT MODIFY COLUMN health_condition SET TAG SECURITY.SPECIAL_CATEGORY='YES';
ALTER VIEW CORE.FACT_CASE MODIFY COLUMN condition_category SET MASKING POLICY SECURITY.MASK_CATEGORY;
ALTER VIEW CORE.FACT_CASE MODIFY COLUMN condition_category SET TAG SECURITY.SPECIAL_CATEGORY='YES';

CREATE TABLE IF NOT EXISTS SECURITY.USER_TEAMS (user_name VARCHAR, team_id VARCHAR);
-- Example only; execute for the actual Snowflake login used by the team-viewer demo:
-- INSERT INTO SECURITY.USER_TEAMS VALUES ('DEMO_TEAM_USER','TEAM_A');
CREATE OR REPLACE ROW ACCESS POLICY SECURITY.CASE_TEAM_POLICY AS (p_team_id VARCHAR)
RETURNS BOOLEAN ->
 IS_ROLE_IN_SESSION('ASSESSMENT_ADMIN') OR IS_ROLE_IN_SESSION('QA_REVIEWER')
 OR (IS_ROLE_IN_SESSION('ASSESSOR_TEAM_VIEWER') AND EXISTS (
   SELECT 1 FROM SECURITY.USER_TEAMS m
   WHERE UPPER(m.user_name)=UPPER(CURRENT_USER()) AND m.team_id=p_team_id));
ALTER VIEW CORE.FACT_CASE ADD ROW ACCESS POLICY SECURITY.CASE_TEAM_POLICY ON (team_id);

GRANT USAGE ON DATABASE PIP_QUALITY TO ROLE ASSESSMENT_ADMIN;
GRANT USAGE ON ALL SCHEMAS IN DATABASE PIP_QUALITY TO ROLE ASSESSMENT_ADMIN;
GRANT SELECT ON ALL TABLES IN SCHEMA PIP_QUALITY.RAW TO ROLE ASSESSMENT_ADMIN;
GRANT SELECT ON ALL VIEWS IN SCHEMA PIP_QUALITY.STAGING TO ROLE ASSESSMENT_ADMIN;
GRANT SELECT ON ALL VIEWS IN SCHEMA PIP_QUALITY.CORE TO ROLE ASSESSMENT_ADMIN;
GRANT SELECT ON ALL VIEWS IN SCHEMA PIP_QUALITY.MART TO ROLE ASSESSMENT_ADMIN;
GRANT SELECT ON TABLE PIP_QUALITY.MART.AUDIT_SAMPLE TO ROLE ASSESSMENT_ADMIN;
GRANT USAGE ON WAREHOUSE PIP_WH TO ROLE ASSESSMENT_ADMIN;

GRANT USAGE ON DATABASE PIP_QUALITY TO ROLE QA_REVIEWER;
GRANT USAGE ON SCHEMA PIP_QUALITY.CORE TO ROLE QA_REVIEWER;
GRANT USAGE ON SCHEMA PIP_QUALITY.MART TO ROLE QA_REVIEWER;
GRANT SELECT ON ALL VIEWS IN SCHEMA PIP_QUALITY.CORE TO ROLE QA_REVIEWER;
GRANT SELECT ON ALL VIEWS IN SCHEMA PIP_QUALITY.MART TO ROLE QA_REVIEWER;
GRANT SELECT ON TABLE PIP_QUALITY.MART.AUDIT_SAMPLE TO ROLE QA_REVIEWER;
GRANT USAGE ON WAREHOUSE PIP_WH TO ROLE QA_REVIEWER;

GRANT USAGE ON DATABASE PIP_QUALITY TO ROLE ASSESSOR_TEAM_VIEWER;
GRANT USAGE ON SCHEMA PIP_QUALITY.CORE TO ROLE ASSESSOR_TEAM_VIEWER;
GRANT USAGE ON SCHEMA PIP_QUALITY.MART TO ROLE ASSESSOR_TEAM_VIEWER;
